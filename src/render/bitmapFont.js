export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;

export function hasGlyph(ch) {
  return Object.hasOwn(G, ch.toUpperCase());
}

/** Width in canvas pixels of `text` at integer `scale`. */
export function textWidth(text, scale = 1) {
  return text.length * ADVANCE * scale;
}

/** Draws `text` with the current fillStyle. Unknown characters draw as blanks. */
export function drawText(ctx, text, x, y, scale = 1) {
  const up = text.toUpperCase();
  for (let i = 0; i < up.length; i++) {
    const rows = G[up[i]];
    if (!rows) continue;
    const gx = x + i * ADVANCE * scale;
    for (let r = 0; r < GLYPH_H; r++) {
      const row = rows[r];
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === '#') ctx.fillRect(gx + c * scale, y + r * scale, scale, scale);
      }
    }
  }
}
